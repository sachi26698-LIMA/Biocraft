/**
 * BioCraft — idempotent Supabase seed generator.
 *
 * Reads the checked-in content registry (the exact data the app ships) and
 * emits deterministic, re-runnable SQL:
 *
 *   supabase/seed/01_platforms.sql
 *   supabase/seed/02_categories.sql
 *   supabase/seed/03_bios.sql
 *   supabase/seed/04_generators.sql
 *   supabase/seed/05_fonts.sql
 *   supabase/seed/06_symbols.sql
 *   supabase/seed/07_emoji_collections.sql
 *   supabase/seed/08_hashtags.sql
 *   supabase/seed/09_captions.sql
 *   supabase/seed/10_seo_pages.sql
 *
 * Every INSERT uses ON CONFLICT so re-running never duplicates. Nothing here
 * invents content: rows are derived from src/ verbatim. Featured/trending
 * flags are intentionally left false — the future admin dashboard sets them.
 *
 * Usage:  node scripts/seed-supabase.mjs
 * Apply:  psql or the seed files in order, then verify counts (printed).
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = dirname(fileURLToPath(new URL('../package.json', import.meta.url)));

// ---------- bundle the data entry (exact registry the app ships) ----------
const bundlePath = join(root, 'node_modules', '.cache', 'seed-data-entry.cjs');
await build({
  entryPoints: [join(root, 'scripts/seed-data-entry.tsx')],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  outfile: bundlePath,
  logLevel: 'silent',
});
const data = await import(pathToFileURL(bundlePath).href);
const { BIO_COLLECTIONS, SYMBOL_CATEGORIES, UNICODE_STYLES, NICHES, TOPICS, TONES, TEMPLATES, TOOLS } = data;
const { applyStyle } = await import(pathToFileURL(bundlePath).href).catch(() => ({}));

// ---------- helpers ----------
const esc = (value) => String(value).replace(/'/g, "''");
const sqlStr = (value) => (value === null || value === undefined ? 'null' : `'${esc(value)}'`);
const sqlBool = (value) => (value ? 'true' : 'false');
const sqlInt = (value) => (value === null || value === undefined ? 'null' : String(Math.trunc(value)));
const DIV = '------------------------------------------------------------\n';

const files = [];
const counts = {};
const emit = (name, lines, table, count) => {
  files.push({ name, sql: [`-- ${DIV}-- ${table} — generated by scripts/seed-supabase.mjs\n${DIV}begin;\n`, ...lines, 'commit;\n'].join('') });
  counts[table] = count;
};

