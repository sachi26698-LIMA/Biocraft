#!/usr/bin/env node
/**
 * Generate public/sitemap.xml from the route shells the build actually emits.
 *
 * There was no sitemap on this site at all — /sitemap.xml returned a 404 while
 * the app served 121 routes. Generating it from `scripts/build-shells.mjs` rather
 * than a hand-written list means the sitemap cannot drift from the real route
 * table: a route that is added gets listed, and a route that is removed stops
 * being listed. That drift is exactly why hand-maintained sitemaps rot.
 *
 * Excluded on purpose:
 *   /admin, /admin/*, /api/*   private console, already Disallow'd in robots.txt
 *   anything not emitted as a shell
 *
 * Usage: node scripts/build-sitemap.mjs [siteUrl]
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SITE = (process.argv[2] || process.env.BIOCRAFT_SITE_URL || 'https://biocraft-bice.vercel.app')
  .replace(/\/+$/, '');

/** Routes are never indexed if they are private or non-navigational. */
const EXCLUDE = [/^\/admin(\/|$)/, /^\/api(\/|$)/];

/** Routes whose content changes when content is added get a higher priority. */
const HIGH = [/^\/$/, /^\/(premium-bios|bio-library|bio-collections|categories)$/, /-generator$/, /^\/library-search$/];

const shellsSrc = readFileSync('scripts/build-shells.mjs', 'utf8');
const routes = new Set([...shellsSrc.matchAll(/'(\/[a-z0-9/-]*)'/g)].map((m) => m[1]));

// The Hindi specimen pages are not literals in build-shells.mjs — they are one
// shell per catalogue entry, expanded at build time. Reading the same catalogue
// keeps the sitemap in step with the 121 shells the build actually emits, rather
// than the 72 that happen to be written out by hand.
try {
  const catalogue = JSON.parse(readFileSync('src/data/hindi-fonts/catalogue.json', 'utf8'));
  for (const font of catalogue.fonts) routes.add(`/hindi-fonts/${font.slug}`);
  console.log(`  + ${catalogue.fonts.length} Hindi specimen routes from the catalogue`);
} catch (error) {
  console.warn(`  ! Hindi catalogue unreadable (${error.message}) — specimen routes omitted`);
}

const listed = [...routes].filter((r) => !EXCLUDE.some((re) => re.test(r))).sort();

if (listed.length === 0) {
  console.error('build-sitemap: no routes found in scripts/build-shells.mjs — refusing to write an empty sitemap');
  process.exit(1);
}

const today = new Date().toISOString().slice(0, 10);
const entries = listed.map((route) => {
  const priority = route === '/' ? '1.0' : HIGH.some((re) => re.test(route)) ? '0.8' : '0.6';
  const changefreq = route === '/' || HIGH.some((re) => re.test(route)) ? 'weekly' : 'monthly';
  return `  <url>\n    <loc>${SITE}${route === '/' ? '/' : route}</loc>\n    <lastmod>${today}</lastmod>\n    <changefreq>${changefreq}</changefreq>\n    <priority>${priority}</priority>\n  </url>`;
});

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-sitemap.mjs from scripts/build-shells.mjs. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries.join('\n')}
</urlset>
`;

writeFileSync('public/sitemap.xml', xml);
console.log(`sitemap: ${listed.length} routes -> public/sitemap.xml (${SITE})`);
