export function categoryLabel(category: WhatsAppStatusCategoryId, language: Language): string {
  const found = STATUS_CATEGORIES.find((item) => item.id === category);
  if (!found) return category;
  if (language === 'hi') return found.labelHi;
  if (language === 'hg') return found.labelHg;
  return found.label;
}
