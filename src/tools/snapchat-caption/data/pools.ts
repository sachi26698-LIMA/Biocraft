export function snapCategoryLabel(category: SnapchatCaptionCategoryId, language: Language): string {
  const found = SNAP_CATEGORIES.find((item) => item.id === category);
  if (!found) return category;
  if (language === 'hi') return found.labelHi;
  if (language === 'hg') return found.labelHg;
  return found.label;
}
